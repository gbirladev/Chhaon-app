-- 9. One schedule per medicine per clock time (a Morning preset plus a custom 08:00 sent the parent two reminders).
delete from public.medicine_schedules a using public.medicine_schedules b
where a.medicine_id = b.medicine_id and a.time_of_day = b.time_of_day and a.id > b.id;
create unique index medicine_schedules_one_per_time on public.medicine_schedules (medicine_id, time_of_day);

-- 10. start_date defaults to the PARENT's local date (the UTC date skipped a first dose for parents west of UTC).
drop function public.create_medicine(uuid, text, text, text, text, integer, integer, time[], date, date);
create function public.create_medicine(
  p_recipient uuid, p_name text, p_dosage text, p_instructions text, p_photo_url text,
  p_stock integer, p_refill_threshold integer, p_times time[],
  p_start date default null, p_end date default null
) returns uuid
language plpgsql security invoker set search_path = '' as $$
declare
  v_medicine uuid;
  v_start date;
begin
  if coalesce(cardinality(p_times), 0) = 0 then
    raise exception 'at least one reminder time is required' using errcode = '22023';
  end if;
  select coalesce(p_start, (now() at time zone r.timezone)::date) into v_start
  from public.care_recipients r where r.id = p_recipient;
  if v_start is null then
    raise exception 'parent not found' using errcode = '42501';
  end if;

  insert into public.medicines (recipient_id, name, dosage, instructions, photo_url, stock_count, refill_threshold)
  values (p_recipient, p_name, p_dosage, p_instructions, p_photo_url, p_stock, p_refill_threshold)
  returning id into v_medicine;

  insert into public.medicine_schedules (medicine_id, time_of_day, start_date, end_date)
  select v_medicine, t, v_start, p_end from (select distinct unnest(p_times) as t) as times;

  return v_medicine;
end $$;
revoke execute on function public.create_medicine(uuid, text, text, text, text, integer, integer, time[], date, date) from public, anon;
grant execute on function public.create_medicine(uuid, text, text, text, text, integer, integer, time[], date, date) to authenticated;

-- 11. Stock changes by the caregiver are deltas, so a stale screen cannot overwrite a dose taken in the meantime.
create function public.adjust_stock(p_medicine uuid, p_delta integer) returns integer
language sql security invoker set search_path = '' as $$
  update public.medicines
  set stock_count = greatest(stock_count + p_delta, 0)
  where id = p_medicine and stock_count is not null
  returning stock_count;
$$;
revoke execute on function public.adjust_stock(uuid, integer) from public, anon;
grant execute on function public.adjust_stock(uuid, integer) to authenticated;

-- 12. generate_dose_events skips recipients with an unknown timezone instead of failing for everyone,
--     and its grace period defaults to the dose window (60 min) so a delayed tick does not drop doses.
create or replace function public.generate_dose_events(
  p_now timestamptz default now(),
  p_horizon interval default '24 hours',
  p_grace interval default '60 minutes'
) returns integer
language plpgsql security definer set search_path = '' as $$
declare
  v_created integer;
begin
  with zones as (select name from pg_catalog.pg_timezone_names),
  candidates as (
    select
      s.id as schedule_id,
      ((d.day + s.time_of_day) at time zone r.timezone) as scheduled_at,
      s.created_at
    from public.medicine_schedules s
    join public.medicines m on m.id = s.medicine_id and m.active
    join public.care_recipients r on r.id = m.recipient_id
    join zones z on z.name = r.timezone
    cross join lateral generate_series(
      ((p_now at time zone r.timezone)::date - 1)::timestamp,
      ((p_now at time zone r.timezone)::date + 2)::timestamp,
      interval '1 day'
    ) as d(day)
    where d.day::date >= s.start_date
      and (s.end_date is null or d.day::date <= s.end_date)
      and extract(dow from d.day)::smallint = any (s.days_of_week)
  ), inserted as (
    insert into public.dose_events (schedule_id, scheduled_at)
    select schedule_id, scheduled_at
    from candidates
    where scheduled_at >= p_now - p_grace
      and scheduled_at <= p_now + p_horizon
      and scheduled_at >= created_at
    on conflict (schedule_id, scheduled_at) do nothing
    returning 1
  )
  select count(*) into v_created from inserted;

  delete from public.dose_events de
  using public.medicine_schedules s, public.medicines m
  where de.schedule_id = s.id and s.medicine_id = m.id
    and de.status = 'pending' and not m.active;

  return v_created;
end $$;
