-- Hardening from the QA round (security + scheduler reviews).

-- 1. A bad timezone must never reach the scheduler: it would make dose generation fail for EVERY family.
create function public.validate_recipient_timezone() returns trigger
language plpgsql set search_path = '' as $$
begin
  begin
    perform now() at time zone new.timezone;
  exception when others then
    raise exception 'unknown time zone: %', new.timezone using errcode = '22023';
  end;
  return new;
end $$;
create trigger care_recipients_validate_timezone
  before insert or update of timezone on public.care_recipients
  for each row execute function public.validate_recipient_timezone();

-- 2. A parent who travels: pending reminders in the old timezone must not fire. Regenerated by the scheduler.
create function public.clear_pending_doses_on_timezone_change() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  if new.timezone is distinct from old.timezone then
    delete from public.dose_events de
    using public.medicine_schedules s, public.medicines m
    where de.schedule_id = s.id and s.medicine_id = m.id and m.recipient_id = new.id
      and de.status = 'pending' and de.scheduled_at > now();
  end if;
  return new;
end $$;
create trigger care_recipients_clear_doses_on_tz_change
  after update of timezone on public.care_recipients
  for each row execute function public.clear_pending_doses_on_timezone_change();

-- 3. consent_requested_at is the rate limit for messaging a parent: only the system may write it.
create or replace function public.guard_recipient_consent() returns trigger
language plpgsql set search_path = '' as $$
begin
  if (select auth.role()) = 'authenticated' then
    if tg_op = 'INSERT' then
      new.consent_at := null;
      new.opted_out_at := null;
      new.consent_requested_at := null;
    elsif new.consent_at is distinct from old.consent_at
       or new.opted_out_at is distinct from old.opted_out_at
       or new.consent_requested_at is distinct from old.consent_requested_at then
      raise exception 'consent fields can only be changed by the system' using errcode = '42501';
    end if;
  end if;
  return new;
end $$;

-- 4. Who may be messaged: per-phone and per-caregiver request log (backend only: RLS on, no policies).
create table public.consent_requests (
  id            uuid primary key default gen_random_uuid(),
  requested_by  uuid references public.profiles (id) on delete set null,
  phone         text not null,
  requested_at  timestamptz not null default now()
);
create index on public.consent_requests (phone, requested_at desc);
create index on public.consent_requests (requested_by, requested_at desc);
alter table public.consent_requests enable row level security;

-- 5. A medicine photo must live in its own parent's folder (the backend signs this path with elevated rights).
alter table public.medicines
  add constraint medicines_photo_in_own_folder
  check (photo_url is null or photo_url like recipient_id::text || '/%') not valid;

-- 6. A circle membership cannot be re-pointed at another user (or circle).
create function public.freeze_membership_identity() returns trigger
language plpgsql set search_path = '' as $$
begin
  if new.user_id is distinct from old.user_id or new.circle_id is distinct from old.circle_id then
    raise exception 'membership cannot be reassigned' using errcode = '42501';
  end if;
  return new;
end $$;
create trigger care_circle_members_freeze_identity
  before update on public.care_circle_members
  for each row execute function public.freeze_membership_identity();

-- 7. "Created by" fields cannot be spoofed.
create function public.stamp_author() returns trigger
language plpgsql set search_path = '' as $$
begin
  if (select auth.role()) = 'authenticated' then
    if tg_table_name = 'reports' then new.uploaded_by := (select auth.uid());
    else new.created_by := (select auth.uid());
    end if;
  end if;
  return new;
end $$;
create trigger reports_stamp_author before insert on public.reports for each row execute function public.stamp_author();
create trigger appointments_stamp_author before insert on public.appointments for each row execute function public.stamp_author();

