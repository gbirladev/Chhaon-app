-- Emergency card link (step 10). Public (no login) reads are served by the backend with the service role, by token.
-- Caregivers manage the link ONLY through the three functions below, so nobody can choose their own (guessable) token
-- or fake the view counters. Revoked links are kept (history); at most one link per parent is active at a time.

alter table public.emergency_links
  add column created_by      uuid references public.profiles (id) on delete set null,
  add column revoked_at      timestamptz,
  add column last_viewed_at  timestamptz,
  add column view_count      integer not null default 0;

-- Old rows (none in practice): keep only the newest active link per parent.
update public.emergency_links l set active = false, revoked_at = now()
 where active and exists (select 1 from public.emergency_links o where o.recipient_id = l.recipient_id and o.active and o.created_at > l.created_at);

create unique index emergency_links_one_active on public.emergency_links (recipient_id) where active;

-- Tokens are generated by the database only; the unique constraint on token already exists.
alter table public.emergency_links add constraint emergency_links_token_shape check (token ~ '^[0-9a-f]{64}$');

revoke insert, update, delete on public.emergency_links from authenticated, anon;

-- Turn the link on (or return the one that is already on). Idempotent.
create function public.enable_emergency_link(p_recipient uuid) returns setof public.emergency_links
language plpgsql security definer set search_path = '' as $$
begin
  if not public.can_access_recipient(p_recipient) then
    raise exception 'not allowed' using errcode = '42501';
  end if;
  insert into public.emergency_links (recipient_id, created_by)
  values (p_recipient, (select auth.uid()))
  on conflict (recipient_id) where active do nothing;
  return query select * from public.emergency_links where recipient_id = p_recipient and active;
end $$;

-- Turn the link off. The old address stops working immediately.
create function public.revoke_emergency_link(p_recipient uuid) returns void
language plpgsql security definer set search_path = '' as $$
begin
  if not public.can_access_recipient(p_recipient) then
    raise exception 'not allowed' using errcode = '42501';
  end if;
  update public.emergency_links set active = false, revoked_at = now() where recipient_id = p_recipient and active;
end $$;

-- Make a new link: the old token dies in the same transaction.
create function public.rotate_emergency_link(p_recipient uuid) returns setof public.emergency_links
language plpgsql security definer set search_path = '' as $$
begin
  if not public.can_access_recipient(p_recipient) then
    raise exception 'not allowed' using errcode = '42501';
  end if;
  update public.emergency_links set active = false, revoked_at = now() where recipient_id = p_recipient and active;
  return query insert into public.emergency_links (recipient_id, created_by) values (p_recipient, (select auth.uid())) returning *;
end $$;

revoke execute on function public.enable_emergency_link(uuid), public.revoke_emergency_link(uuid), public.rotate_emergency_link(uuid) from public, anon;
grant execute on function public.enable_emergency_link(uuid), public.revoke_emergency_link(uuid), public.rotate_emergency_link(uuid) to authenticated;
