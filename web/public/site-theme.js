/* Public website (home, /hi/, doctors, legal): applies the appearance before the first paint, wires the header picker and keeps
   the browser-tab icon and the browser's bar colour in the chosen colours.
   Loaded synchronously in <head> after /site-theme.css, as a file (the production CSP is script-src 'self': no inline scripts).
   The setting is SHARED with the app (same origin, same keys and attributes as src/lib/theme.ts, src/lib/palette.ts and
   public/theme.js), so a choice on either side carries over:
     chhaon-theme          "light" | "dark" | absent (= follow the device)                  -> <html data-theme>
     chhaon-palette        absent (= Chhaon violet) | classic | teal | blue | saffron | rose | custom -> <html data-palette>
     chhaon-palette-custom the picked custom colour, #rrggbb
     chhaon-palette-css    the APP's CSS for that custom colour (src/lib/recolour.ts). The site cannot build it (different tokens),
                           so when the site picks a new custom colour it removes it and the app rebuilds it on its next start.
   The site's own custom-colour CSS is built here from SITE_TOKENS (the site's violet tokens) with the app's maths. */
(function () {
  var root = document.documentElement;

  // Home page only (<html data-site="home">): old links and old home-screen icons.
  if (root.getAttribute("data-site") === "home") {
    // Emergency-card and family-invite links shared before the app moved to /app looked like chhaon.site/#/e/<token> or
    // #/join/<token>. Send them on to the app unchanged. hashchange covers a link pasted into a tab that already shows the page.
    var forward = function () { if (/^#\/(e|join)\//.test(location.hash)) location.replace("/app/" + location.hash); };
    forward();
    window.addEventListener("hashchange", forward);
    // An icon added to the home screen while the app lived at "/" still opens "/". Opened as an installed app (its own window,
    // not a browser tab), send it straight on to the app instead of showing the website. Normal visitors are not affected.
    var installed = (window.matchMedia && window.matchMedia("(display-mode: standalone)").matches) || window.navigator.standalone === true;
    if (installed && location.pathname === "/") location.replace("/app/" + location.search + location.hash);
  }

  var THEME_KEY = "chhaon-theme", PALETTE_KEY = "chhaon-palette", CUSTOM_KEY = "chhaon-palette-custom", APP_CSS_KEY = "chhaon-palette-css";
  // Same list, order and default custom colour as PALETTES / DEFAULT_CUSTOM in src/lib/palette.ts.
  var PALETTES = ["chhaon", "classic", "teal", "blue", "saffron", "rose"];
  var DEFAULT_CUSTOM = "#e0457b";
  var STYLE_ID = "chhaon-site-custom";
  // GENERATED by scripts/build-site-palettes.mjs from /site-theme.css (the violet tokens, light and dark). Do not edit by hand.
  var SITE_TOKENS = {"light":[["--bg","#faf8fc"],["--surface","#ffffff"],["--ink","#1d1928"],["--muted","#555061"],["--line","#e5e2eb"],["--primary","#6943a5"],["--primary-hover","#563489"],["--primary-2","#8463bd"],["--pt","#6943a5"],["--mint","#f4f1fb"],["--mint-2","#faf8fc"],["--tick-bg","#e9e2f5"],["--hero-a","#fdf0dc"],["--hero-b","#fbf7f0"],["--hero-c","#f3eefa"],["--glow-cool","rgba(105, 67, 165, .16)"],["--art-a","#ffe3b0"],["--art-b","#ebe5f5"],["--band","#2a2140"],["--band-2","#3f2964"],["--band-muted","#cdc4de"],["--band-kicker","#d5c6f7"],["--bar-bg","rgba(250, 248, 252, .86)"],["--final-a","#6943a5"],["--final-b","#8463bd"],["--final-muted","#efeaf8"],["--dash","#bbb5c6"]],"dark":[["--bg","#131119"],["--surface","#1b1822"],["--ink","#eceaf1"],["--muted","#c2bdcc"],["--line","#312c3b"],["--primary","#7655c2"],["--primary-hover","#8466cc"],["--primary-2","#6943a5"],["--pt","#c3b8eb"],["--mint","#18151f"],["--mint-2","#131119"],["--tick-bg","#2d2640"],["--hero-a","#1d1824"],["--hero-b","#18151f"],["--hero-c","#15121c"],["--glow-cool","rgba(136, 104, 210, .12)"],["--art-a","#2a2233"],["--art-b","#1f1b29"],["--band","#0e0c13"],["--band-2","#221d2c"],["--band-muted","#c2bdcc"],["--band-kicker","#c3b8eb"],["--bar-bg","rgba(19, 17, 25, .88)"],["--final-a","#4f3485"],["--final-b","#6943a5"],["--final-muted","#e3dcf2"],["--dash","#4a4456"]]};

  function read(key) { try { return localStorage.getItem(key); } catch (e) { return null; } }
  function write(key, value) { try { if (value === null) localStorage.removeItem(key); else localStorage.setItem(key, value); } catch (e) { /* storage blocked: applies until the page closes */ } }
  function themeChoice() { var t = read(THEME_KEY); return t === "light" || t === "dark" ? t : "system"; }
  function paletteChoice() { var p = read(PALETTE_KEY); return p === "custom" || (p && PALETTES.indexOf(p) > 0) ? p : "chhaon"; }
  function customColour() { var c = read(CUSTOM_KEY); return c && /^#[0-9a-f]{6}$/i.test(c) ? c.toLowerCase() : DEFAULT_CUSTOM; }
  var mq = window.matchMedia ? window.matchMedia("(prefers-color-scheme: dark)") : null;

  // ---- Custom colour: the site's violet tokens turned to the picked hue, each keeping its brightness (relative luminance), so
  // text keeps the contrast it has in violet. Same maths as src/lib/recolour.ts and scripts/build-site-palettes.mjs: keep in step.
  // The site's violet is the app's softened one (DEFAULT_SOFTEN 0.6 in scripts/build-palettes.mjs), hence the "/ SITE_SOFTEN".
  var SITE_SOFTEN = 0.6;
  function hexToRgb(hex) { return [0, 2, 4].map(function (i) { return parseInt(hex.slice(i, i + 2), 16) / 255; }); }
  function rgbToHex(rgb) { return rgb.map(function (v) { return ("0" + Math.round(Math.min(1, Math.max(0, v)) * 255).toString(16)).slice(-2); }).join(""); }
  function rgbToHsl(c) {
    var r = c[0], g = c[1], b = c[2], max = Math.max(r, g, b), min = Math.min(r, g, b), l = (max + min) / 2;
    if (max === min) return [0, 0, l];
    var d = max - min, s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
    var h = max === r ? (g - b) / d + (g < b ? 6 : 0) : max === g ? (b - r) / d + 2 : (r - g) / d + 4;
    return [h * 60, s, l];
  }
  function hslToRgb(h, s, l) {
    var a = s * Math.min(l, 1 - l);
    return [0, 8, 4].map(function (n) { var k = (n + h / 30) % 12; return l - a * Math.max(-1, Math.min(k - 3, 9 - k, 1)); });
  }
  function lin(v) { return v <= 0.03928 ? v / 12.92 : Math.pow((v + 0.055) / 1.055, 2.4); }
  function luminance(rgb) { return 0.2126 * lin(rgb[0]) + 0.7152 * lin(rgb[1]) + 0.0722 * lin(rgb[2]); }
  function shift(hex, target) {
    var rgb = hexToRgb(hex), hsl = rgbToHsl(rgb);
    if (!(hsl[0] >= 235 && hsl[0] <= 305 && hsl[1] >= 0.06)) return null;   // only the violet family changes
    var goal = luminance(rgb), ns = Math.min(1, hsl[1] * target.sat), lo = 0, hi = 1;
    for (var i = 0; i < 30; i++) { var mid = (lo + hi) / 2; if (luminance(hslToRgb(target.hue, ns, mid)) < goal) lo = mid; else hi = mid; }
    return rgbToHex(hslToRgb(target.hue, ns, (lo + hi) / 2));
  }
  function recolour(value, target) {
    return value
      .replace(/#([0-9a-fA-F]{6})\b/g, function (m, hex) { var out = shift(hex, target); return out ? "#" + out : m; })
      .replace(/rgba?\((\d+),\s*(\d+),\s*(\d+)((?:,\s*[\d.]+)?)\)/g, function (m, r, g, b, alpha) {
        var out = shift([r, g, b].map(function (v) { return ("0" + Number(v).toString(16)).slice(-2); }).join(""), target);
        if (!out) return m;
        var n = hexToRgb(out).map(function (v) { return Math.round(v * 255); });
        return (alpha ? "rgba" : "rgb") + "(" + n.join(",") + alpha.replace(/\s/g, "") + ")";
      });
  }
  // The picked colour as a hue and a saturation factor (targetOf in src/lib/recolour.ts), scaled for the softened site violet.
  function targetOf(picked) {
    var hsl = rgbToHsl(hexToRgb(picked.slice(1)));
    return { hue: hsl[0], sat: Math.min(1.3, hsl[1] / 0.7) / SITE_SOFTEN };
  }
  function customCss(picked) {
    var t = targetOf(picked);
    var lines = function (list) { return list.map(function (p) { return p[0] + ":" + recolour(p[1], t) + ";"; }).join(""); };
    var dark = lines(SITE_TOKENS.dark);
    return ':root[data-palette="custom"]{' + lines(SITE_TOKENS.light) + "}"
      + '@media screen{:root[data-palette="custom"][data-theme="dark"]{' + dark + "}}"
      + '@media screen and (prefers-color-scheme: dark){:root[data-palette="custom"]:not([data-theme="light"]){' + dark + "}}";
  }
  var builtFor = null;
  function setCustomStyle(css) {
    var el = document.getElementById(STYLE_ID);
    if (!css) { if (el) el.parentNode.removeChild(el); return; }
    if (!el) { el = document.createElement("style"); el.id = STYLE_ID; document.head.appendChild(el); }
    el.textContent = css;
  }

  // ---- Browser-tab icon: logo C (src/lib/logo.ts) in the page's current --primary / --on-primary, as a data URL in the SVG
  // <link rel="icon">. Anything that is not a plain colour falls back to the static violet /favicon.svg.
  var plain = /^(#[0-9a-f]{3,8}|rgba?\([\d\s.,%\/]+\))$/i;
  function logoSvg(tile, ink) {
    return '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64"><rect width="64" height="64" rx="14" fill="' + tile + '"/>'
      + '<path fill="none" stroke="' + ink + '" stroke-width="5.5" stroke-linecap="round" stroke-linejoin="round" d="M13 30 32 14l19 16"/>'
      + '<path fill="' + ink + '" d="M32 50 21.5 40a6.6 6.6 0 0 1 9.3-9.4l1.2 1.1 1.2-1.1a6.6 6.6 0 0 1 9.3 9.4Z"/></svg>';
  }
  function updateTabIcon(style) {
    var tile = style.getPropertyValue("--primary").trim(), ink = style.getPropertyValue("--on-primary").trim() || "#ffffff";
    var link = document.querySelector('link[rel="icon"][type="image/svg+xml"]');
    if (!link) {
      link = document.createElement("link");
      link.rel = "icon"; link.type = "image/svg+xml"; link.setAttribute("sizes", "any");
      document.head.appendChild(link);
    }
    var href = plain.test(tile) && plain.test(ink) ? "data:image/svg+xml," + encodeURIComponent(logoSvg(tile, ink)) : "/favicon.svg";
    if (link.getAttribute("href") !== href) link.setAttribute("href", href);
  }

  function paint() {
    var t = themeChoice(), p = paletteChoice();
    if (t === "system") { root.removeAttribute("data-theme"); root.style.removeProperty("color-scheme"); }
    else { root.setAttribute("data-theme", t); root.style.colorScheme = t; }
    if (p === "custom") { var c = customColour(); if (builtFor !== c) { setCustomStyle(customCss(c)); builtFor = c; } }
    else if (builtFor !== null) { setCustomStyle(null); builtFor = null; }
    if (p === "chhaon") root.removeAttribute("data-palette"); else root.setAttribute("data-palette", p);
    // The browser's bar and the tab icon follow the colours really shown (light or dark included).
    var style = getComputedStyle(root);
    var bg = style.getPropertyValue("--bg").trim();
    var meta = document.querySelector('meta[name="theme-color"]');
    if (meta && plain.test(bg)) meta.setAttribute("content", bg);
    updateTabIcon(style);
    // The menu, once it exists.
    var buttons = document.querySelectorAll("[data-ap-palette], [data-ap-theme]");
    for (var i = 0; i < buttons.length; i++) {
      var b = buttons[i], v = b.getAttribute("data-ap-palette") || b.getAttribute("data-ap-theme");
      b.setAttribute("aria-pressed", String(v === p || v === t));
    }
    var cus = document.getElementById("ap-custom");
    if (cus) {
      var on = p === "custom", input = cus.querySelector("input"), sw = cus.querySelector(".ap-sw");
      cus.classList.toggle("on", on);
      if (input && document.activeElement !== input) input.value = customColour();
      if (sw) sw.style.background = on ? "#" + (shift("6943a5", targetOf(customColour())) || "6943a5") : "";
    }
  }
  paint();
  if (mq && mq.addEventListener) mq.addEventListener("change", paint);
  // Another tab (the app or the site) changed the setting.
  window.addEventListener("storage", function (e) { if (e.key === THEME_KEY || e.key === PALETTE_KEY || e.key === CUSTOM_KEY || e.key === null) paint(); });
  // Back/forward cache: the setting may have changed in the app meanwhile.
  window.addEventListener("pageshow", paint);

  function wire() {
    var btn = document.getElementById("ap-btn"), menu = document.getElementById("ap-menu");
    paint();
    if (!btn || !menu) return;
    function open(yes) {
      menu.hidden = !yes;
      btn.setAttribute("aria-expanded", String(yes));
      if (yes) { var first = menu.querySelector('button[aria-pressed="true"]') || menu.querySelector("button"); if (first) first.focus(); }
    }
    btn.addEventListener("click", function () { open(menu.hidden); });
    menu.addEventListener("click", function (e) {
      var b = e.target.closest ? e.target.closest("button") : null;
      if (!b) return;
      var p = b.getAttribute("data-ap-palette"), t = b.getAttribute("data-ap-theme");
      if (p) write(PALETTE_KEY, p === "chhaon" ? null : p);
      if (t) write(THEME_KEY, t === "system" ? null : t);
      paint();
    });
    // Custom: the colour input inside the "Custom" tile (it opens the device's colour picker), like the app.
    var input = menu.querySelector("#ap-custom input");
    if (input) {
      var pick = function () {
        var c = String(input.value).toLowerCase();
        if (!/^#[0-9a-f]{6}$/.test(c)) return;
        // The app's CSS for an older colour would be wrong now: the app rebuilds it from chhaon-palette-custom on its next start.
        if (c !== read(CUSTOM_KEY)) write(APP_CSS_KEY, null);
        write(CUSTOM_KEY, c);
        write(PALETTE_KEY, "custom");
        paint();
      };
      input.addEventListener("input", pick);
      input.addEventListener("change", pick);
    }
    document.addEventListener("keydown", function (e) {
      if (e.key === "Escape" && !menu.hidden) { open(false); btn.focus(); }
    });
    document.addEventListener("click", function (e) {
      if (!menu.hidden && !menu.contains(e.target) && !btn.contains(e.target)) open(false);
    });
    // Keyboard: leaving the menu with Tab closes it.
    menu.addEventListener("focusout", function (e) {
      if (e.relatedTarget && !menu.contains(e.relatedTarget) && e.relatedTarget !== btn) open(false);
    });
  }
  if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", wire); else wire();
})();
