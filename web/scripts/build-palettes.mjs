// Generates src/palettes.css: the extra colour themes a caregiver can pick (Family tab, top right).
// The Smart Gurukul violet in src/theme.css stays the default. Every other theme takes the same tokens and turns
// only the violet family to its own hue, keeping each colour's brightness (relative luminance) the same. So every
// text/background pair keeps the contrast it has in the default theme. Red, green, amber and greys are left alone.
// Run after editing theme.css:  node scripts/build-palettes.mjs   (also run by npm run build)
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const src = join(here, "..", "src");
// Keep in step with PALETTES in src/lib/palette.ts. sat = how much of the original saturation to keep.
const PALETTES = { teal: { hue: 174, sat: 0.85 }, blue: { hue: 214, sat: 0.9 }, green: { hue: 145, sat: 0.75 }, saffron: { hue: 28, sat: 0.95 }, rose: { hue: 340, sat: 0.85 } };
const VIOLET = (h, s) => h >= 235 && h <= 305 && s >= 0.06;

const theme = readFileSync(join(src, "theme.css"), "utf8");

// ---- colour maths
const hexToRgb = (hex) => [0, 2, 4].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255);
const rgbToHex = (rgb) => rgb.map((v) => Math.round(Math.min(1, Math.max(0, v)) * 255).toString(16).padStart(2, "0")).join("");
function rgbToHsl([r, g, b]) {
  const max = Math.max(r, g, b), min = Math.min(r, g, b), l = (max + min) / 2;
  if (max === min) return [0, 0, l];
  const d = max - min, s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
  const h = max === r ? (g - b) / d + (g < b ? 6 : 0) : max === g ? (b - r) / d + 2 : (r - g) / d + 4;
  return [h * 60, s, l];
}
function hslToRgb([h, s, l]) {
  const k = (n) => (n + h / 30) % 12, a = s * Math.min(l, 1 - l);
  return [0, 8, 4].map((n) => l - a * Math.max(-1, Math.min(k(n) - 3, 9 - k(n), 1)));
}
const lin = (v) => (v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4);
const luminance = (rgb) => 0.2126 * lin(rgb[0]) + 0.7152 * lin(rgb[1]) + 0.0722 * lin(rgb[2]);

/** The same colour turned to `hue`, with the lightness searched so its luminance matches the original. */
function shift(hex, { hue, sat }) {
  const rgb = hexToRgb(hex);
  const [h, s] = rgbToHsl(rgb);
  if (!VIOLET(h, s)) return null;
  const target = luminance(rgb), ns = s * sat;
  let lo = 0, hi = 1;
  for (let i = 0; i < 40; i++) {
    const mid = (lo + hi) / 2;
    if (luminance(hslToRgb([hue, ns, mid])) < target) lo = mid; else hi = mid;
  }
  return rgbToHex(hslToRgb([hue, ns, (lo + hi) / 2]));
}

function recolour(value, palette) {
  return value
    .replace(/#([0-9a-fA-F]{6})\b/g, (m, hex) => { const out = shift(hex, palette); return out ? `#${out}` : m; })
    .replace(/%23([0-9a-fA-F]{6})/g, (m, hex) => { const out = shift(hex, palette); return out ? `%23${out}` : m; })
    .replace(/rgba?\((\d+),\s*(\d+),\s*(\d+)((?:,\s*[\d.]+)?)\)/g, (m, r, g, b, alpha) => {
      const hex = [r, g, b].map((v) => Number(v).toString(16).padStart(2, "0")).join("");
      const out = shift(hex, palette);
      if (!out) return m;
      const [nr, ng, nb] = hexToRgb(out).map((v) => Math.round(v * 255));
      return `${alpha ? "rgba" : "rgb"}(${nr},${ng},${nb}${alpha.replace(/\s/g, "")})`;
    });
}

// ---- the three blocks of theme.css: light (:root), forced dark, and system dark
function block(startMarker) {
  const start = theme.indexOf(startMarker);
  if (start < 0) throw new Error(`theme.css: "${startMarker}" not found`);
  const open = theme.indexOf("{", start);
  let depth = 0, i = open;
  for (; i < theme.length; i++) { if (theme[i] === "{") depth++; else if (theme[i] === "}" && --depth === 0) break; }
  return theme.slice(open + 1, i);
}
const tokens = (body) => [...body.matchAll(/^\s*(--[\w-]+)\s*:\s*([^;]+);/gm)].map(([, name, value]) => [name, value.trim()]);
const LIGHT = tokens(block(":root {"));
const DARK = tokens(block(':root[data-theme="dark"] {'));
const SYSTEM_DARK = tokens(block(':root:not([data-theme="light"]):not([data-theme="dark"]) {'));

function changed(list, palette, indent) {
  return list.map(([name, value]) => [name, value, recolour(value, palette)])
    .filter(([, value, next]) => value !== next)
    .map(([name, , next]) => `${indent}${name}: ${next};`).join("\n");
}

let css = `/* GENERATED by scripts/build-palettes.mjs from src/theme.css. Do not edit by hand: edit theme.css and re-run.
   Extra colour themes (Family tab, top right). With no data-palette attribute the Smart Gurukul violet of theme.css applies:
   that is the default, and "Smart Gurukul" in the picker simply removes the attribute. Only the violet family changes here. */
`;
for (const [name, palette] of Object.entries(PALETTES)) {
  css += `
:root[data-palette="${name}"] {
${changed(LIGHT, palette, "  ")}
}
@media screen {
  :root[data-palette="${name}"][data-theme="dark"] {
${changed(DARK, palette, "    ")}
  }
  @media (prefers-color-scheme: dark) {
    :root[data-palette="${name}"]:not([data-theme="light"]):not([data-theme="dark"]) {
${changed(SYSTEM_DARK, palette, "      ")}
    }
  }
}
`;
}
writeFileSync(join(src, "palettes.css"), css);

// A quick contrast report for the most important pair: white text on the primary button.
const contrast = (a, b) => { const [x, y] = [luminance(hexToRgb(a)), luminance(hexToRgb(b))].sort((p, q) => q - p); return (x + 0.05) / (y + 0.05); };
const primary = LIGHT.find(([n]) => n === "--primary")[1].slice(1);
for (const [name, palette] of Object.entries(PALETTES)) {
  const p = shift(primary, palette) ?? primary;
  console.log(`palettes.css: ${name.padEnd(8)} primary #${p}  white-on-primary ${contrast(p, "ffffff").toFixed(2)}:1`);
}
console.log(`palettes.css: default  primary #${primary}  white-on-primary ${contrast(primary, "ffffff").toFixed(2)}:1`);
