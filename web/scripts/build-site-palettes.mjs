// Generates the website's copies of the app's colour themes (Teal, Blue, Saffron, Rose) at the end of public/site-theme.css,
// and the token list that public/site-theme.js turns to a "Custom" colour in the browser.
// Run: node scripts/build-site-palettes.mjs   (also run by npm run build). Edit the hand-written part of site-theme.css, never
// the generated part at its end.
//
// The website has its own tokens (public/site-theme.css), not the app's. Its default violet is already the app's softened violet
// (src/palettes.css, DEFAULT_SOFTEN 0.6 in scripts/build-palettes.mjs). Each theme here turns only the violet family of those
// tokens to the theme's hue with the same maths as scripts/build-palettes.mjs: same hue, saturation scaled, brightness (relative
// luminance) kept, so every text keeps the contrast it has in violet. Because the site's violet is the softened one, the
// saturation factor is divided by DEFAULT_SOFTEN: that gives the same colours as the app (teal primary #19625b, as in the app).
// "Classic" stays hand-written in site-theme.css (the first teal, exact values), like in the app.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const pub = join(dirname(fileURLToPath(import.meta.url)), "..", "public");
const CSS_FILE = join(pub, "site-theme.css"), JS_FILE = join(pub, "site-theme.js");
// Keep in step with PALETTES in scripts/build-palettes.mjs (and src/lib/palette.ts) and with SITE_SOFTEN in public/site-theme.js.
const PALETTES = { teal: { hue: 174, sat: 0.85 }, blue: { hue: 214, sat: 0.9 }, saffron: { hue: 28, sat: 0.95 }, rose: { hue: 340, sat: 0.85 } };
const DEFAULT_SOFTEN = 0.6;
const MARK = "/* ===== GENERATED by scripts/build-site-palettes.mjs";

// ---- colour maths (same as scripts/build-palettes.mjs and public/site-theme.js: keep in step)
const VIOLET = (h, s) => h >= 235 && h <= 305 && s >= 0.06;
const hexToRgb = (hex) => [0, 2, 4].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255);
const rgbToHex = (rgb) => rgb.map((v) => Math.round(Math.min(1, Math.max(0, v)) * 255).toString(16).padStart(2, "0")).join("");
function rgbToHsl([r, g, b]) {
  const max = Math.max(r, g, b), min = Math.min(r, g, b), l = (max + min) / 2;
  if (max === min) return [0, 0, l];
  const d = max - min, s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
  const h = max === r ? (g - b) / d + (g < b ? 6 : 0) : max === g ? (b - r) / d + 2 : (r - g) / d + 4;
  return [h * 60, s, l];
}
function hslToRgb([h, s, l]) {
  const k = (n) => (n + h / 30) % 12, a = s * Math.min(l, 1 - l);
  return [0, 8, 4].map((n) => l - a * Math.max(-1, Math.min(k(n) - 3, 9 - k(n), 1)));
}
const lin = (v) => (v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4);
const luminance = (rgb) => 0.2126 * lin(rgb[0]) + 0.7152 * lin(rgb[1]) + 0.0722 * lin(rgb[2]);
function shift(hex, { hue, sat }) {
  const rgb = hexToRgb(hex);
  const [h, s] = rgbToHsl(rgb);
  if (!VIOLET(h, s)) return null;
  const goal = luminance(rgb), ns = Math.min(1, s * sat);
  let lo = 0, hi = 1;
  for (let i = 0; i < 30; i++) {
    const mid = (lo + hi) / 2;
    if (luminance(hslToRgb([hue, ns, mid])) < goal) lo = mid; else hi = mid;
  }
  return rgbToHex(hslToRgb([hue, ns, (lo + hi) / 2]));
}
function recolour(value, target) {
  return value
    .replace(/#([0-9a-fA-F]{6})\b/g, (m, hex) => { const out = shift(hex, target); return out ? `#${out}` : m; })
    .replace(/rgba?\((\d+),\s*(\d+),\s*(\d+)((?:,\s*[\d.]+)?)\)/g, (m, r, g, b, alpha) => {
      const out = shift([r, g, b].map((v) => Number(v).toString(16).padStart(2, "0")).join(""), target);
      if (!out) return m;
      const [nr, ng, nb] = hexToRgb(out).map((v) => Math.round(v * 255));
      return `${alpha ? "rgba" : "rgb"}(${nr},${ng},${nb}${alpha.replace(/\s/g, "")})`;
    });
}
const contrast = (a, b) => { const [x, y] = [luminance(hexToRgb(a.slice(1))), luminance(hexToRgb(b.slice(1)))].sort((p, q) => q - p); return (x + 0.05) / (y + 0.05); };

// ---- the hand-written violet tokens of site-theme.css
const full = readFileSync(CSS_FILE, "utf8");
const at = full.indexOf(MARK);
const hand = (at < 0 ? full : full.slice(0, at)).trimEnd() + "\n";
function block(marker) {
  const start = hand.indexOf(marker);
  if (start < 0) throw new Error(`build-site-palettes: "${marker}" not found in site-theme.css`);
  const open = hand.indexOf("{", start);
  return hand.slice(open + 1, hand.indexOf("}", open));
}
const tokens = (body) => [...body.matchAll(/(--[\w-]+)\s*:\s*([^;]+);/g)].map(([, name, value]) => [name, value.trim()]);
const LIGHT = tokens(block(":root {"));
const DARK = tokens(block(':root[data-theme="dark"] {'));
const SYSTEM_DARK = tokens(block(':root:not([data-theme="light"]) {'));
if (JSON.stringify(DARK) !== JSON.stringify(SYSTEM_DARK)) throw new Error("build-site-palettes: the two dark blocks of site-theme.css differ; keep them identical");

// Tokens of the violet family (in light or in dark). The dark blocks repeat every one of them, even one that is not violet in
// dark, so a light value of a theme never leaks into dark mode (the light and dark rules have the same specificity).
const violet = (value) => recolour(value, { hue: 0, sat: 1 }) !== value;
const names = new Set([...LIGHT, ...DARK].filter(([, v]) => violet(v)).map(([n]) => n));
const lightList = LIGHT.filter(([n]) => names.has(n));
const darkList = DARK.filter(([n]) => names.has(n));

const siteTarget = ({ hue, sat }) => ({ hue, sat: sat / DEFAULT_SOFTEN });
const decl = (list, target, indent) => list.map(([n, v]) => `${indent}${n}: ${recolour(v, target)};`).join("\n");
const value = (list, target, name) => recolour(list.find(([n]) => n === name)[1], target);

let css = `${MARK}: do not edit below this line. =====
   The app's ready-made colour themes on the website (same names, order and hues as src/lib/palette.ts). Re-run the script after
   changing the violet tokens above. "Custom" is built in the browser by /site-theme.js from the same tokens. */
`;
const problems = [];
const swatches = [];
for (const [name, palette] of Object.entries(PALETTES)) {
  const t = siteTarget(palette);
  css += `
:root[data-palette="${name}"] {
${decl(lightList, t, "  ")}
}
@media screen {
  :root[data-palette="${name}"][data-theme="dark"] {
${decl(darkList, t, "    ")}
  }
}
@media screen and (prefers-color-scheme: dark) {
  :root[data-palette="${name}"]:not([data-theme="light"]) {
${decl(darkList, t, "    ")}
  }
}
`;
  swatches.push(`.ap-sw.${name} { background: ${value(lightList, t, "--primary")}; }`);
  // The pairs that must stay readable: white (on-primary) text on buttons, primary-coloured text on the page and on cards.
  for (const [mode, list] of [["light", LIGHT], ["dark", DARK]]) {
    const get = (n) => recolour((list.find(([k]) => k === n) || LIGHT.find(([k]) => k === n))[1], t);
    const pairs = [["--on-primary", "--primary"], ["--pt", "--bg"], ["--pt", "--surface"]];
    const report = pairs.map(([a, b]) => { const c = contrast(get(a), get(b)); if (c < 4.5) problems.push(`${name} ${mode} ${a} on ${b} ${c.toFixed(2)}:1`); return `${a.slice(2)}/${b.slice(2)} ${c.toFixed(2)}`; });
    console.log(`site-theme.css: ${name.padEnd(8)} ${mode.padEnd(5)} primary ${get("--primary")}  ${report.join("  ")}`);
  }
}
css += `\n/* Swatches in the menu: each theme's light primary (the same as PALETTE_SWATCH in src/lib/palette.ts). */\n${swatches.join("\n")}\n`;
if (problems.length) throw new Error(`build-site-palettes: contrast below 4.5:1: ${problems.join("; ")}`);
writeFileSync(CSS_FILE, `${hand}\n${css}`);

// The token list for "Custom" in public/site-theme.js (one generated line).
const js = readFileSync(JS_FILE, "utf8");
const line = /^ {2}var SITE_TOKENS = .*;$/m;
if (!line.test(js)) throw new Error("build-site-palettes: no `var SITE_TOKENS = …;` line in site-theme.js");
const next = js.replace(line, `  var SITE_TOKENS = ${JSON.stringify({ light: lightList, dark: darkList })};`);
if (next !== js) writeFileSync(JS_FILE, next);
